# 01 - types()
# Estos son los tipos de datos de Python
# int, float, complex, str, bool, NoneType, list, tuple, dict, range, set

print('int:')
print(type(1))

print('float:')
print(type(1.5))

# Es para numeros q desconoces (ecuaciones ?);
print('complex:')
print(type(1 + 2j))

print('str')
print('Hola')

print('Boolean:')
print(type(True))
print(type(False))

# El unico valor que tiene python para definir ausencia...
print('NoneType')
print(type(None))

